"""Small, dependency-free helpers shared across the project."""

from __future__ import annotations

import math
import re
from collections import Counter
from collections.abc import Iterable
from pathlib import Path

_LABEL_RE = re.compile(r"^[a-z0-9_-]+$")


def shannon_entropy(value: str) -> float:
    """Return the Shannon entropy (bits/character) of ``value``.

    Random-looking labels generated by DGAs usually have a much higher
    entropy than human-readable names such as ``www`` or ``mail``.
    """
    if not value:
        return 0.0
    counts = Counter(value.lower())
    length = len(value)
    return -sum((n / length) * math.log2(n / length) for n in counts.values())


def domain_labels(domain: str) -> list[str]:
    """Split a domain into lowercase labels, dropping the root dot."""
    return [label for label in domain.lower().rstrip(".").split(".") if label]


def registered_domain(domain: str) -> str:
    """Return the last two labels (a pragmatic eTLD+1 approximation)."""
    labels = domain_labels(domain)
    return ".".join(labels[-2:]) if len(labels) >= 2 else domain.lower()


def subdomain_depth(domain: str) -> int:
    """Number of labels before the approximated registrable domain."""
    return max(0, len(domain_labels(domain)) - 2)


def longest_label(domain: str) -> str:
    labels = domain_labels(domain)
    return max(labels, key=len, default="")


def looks_like_ip(domain: str) -> bool:
    """True for reverse-DNS pointers and literal IPv4 queries."""
    value = domain.rstrip(".")
    if value.endswith(".in-addr.arpa") or value.endswith(".ip6.arpa"):
        return True
    parts = value.split(".")
    return len(parts) == 4 and all(part.isdigit() for part in parts)


def severity_rank(severity: str) -> int:
    """Higher number means more severe (used for filtering alerts)."""
    return {"info": 0, "low": 1, "medium": 2, "high": 3, "critical": 4}.get(
        severity.lower(), 0
    )


def ensure_parent(path: str | Path) -> Path:
    """Create the parent directory of ``path`` if needed and return a Path."""
    result = Path(path).expanduser()
    if result.parent != Path("."):
        result.parent.mkdir(parents=True, exist_ok=True)
    return result


def chunked(items: Iterable, size: int) -> Iterable[list]:
    """Yield successive ``size``-sized chunks from ``items``."""
    chunk: list = []
    for item in items:
        chunk.append(item)
        if len(chunk) >= size:
            yield chunk
            chunk = []
    if chunk:
        yield chunk


def is_punycode(label: str) -> bool:
    return label.startswith("xn--") and bool(_LABEL_RE.match(label))
